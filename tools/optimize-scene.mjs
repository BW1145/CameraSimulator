import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {dedup,flatten,join,weld,prune,simplify,meshopt,inspect,textureCompress} from '@gltf-transform/functions';
import {MeshoptEncoder,MeshoptDecoder,MeshoptSimplifier} from 'meshoptimizer';
import sharp from 'sharp';
import {readFile,writeFile,stat} from 'node:fs/promises';
import path from 'node:path';
const folder=process.argv[2];if(!folder)throw Error('Usage: node tools/optimize-scene.mjs public/scenes/classroom');
await MeshoptEncoder.ready;
await MeshoptSimplifier.ready;
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
const file=path.join(folder,'scene.glb'),doc=await io.read(file);
await doc.transform(dedup(),flatten(),join(),weld(),prune());
const count=inspect(doc).meshes.properties.reduce((sum,m)=>sum+m.glPrimitives,0);
if(count>650000)await doc.transform(simplify({simplifier:MeshoptSimplifier,ratio:650000/count,error:0.01,lockBorder:true}));
await doc.transform(meshopt({encoder:MeshoptEncoder,level:'medium'}));
await doc.transform(textureCompress({encoder:sharp,targetFormat:'webp',resize:[1024,1024],quality:80}));
await io.write(file,doc);
const report=inspect(doc),meta=JSON.parse(await readFile(path.join(folder,'model.json'),'utf8'));
meta.bytes=(await stat(file)).size;
meta.optimization='Deduplicated, flattened, joined by material, welded, simplified toward 650k triangles with 1% error bound, quantized and Meshopt compressed.';
meta.meshes=report.meshes.properties.length;meta.materials=report.materials.properties.length;
meta.triangles=report.meshes.properties.reduce((sum,m)=>sum+m.glPrimitives,0);
meta.textures=report.textures.properties.length;
await writeFile(path.join(folder,'model.json'),JSON.stringify(meta,null,2)+'\n');
console.log(JSON.stringify(meta,null,2));
